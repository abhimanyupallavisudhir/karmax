// Run with node scripts/generate-check-knot-tilted.mjs.
// Project the original knot as one plane, then fit its overall size to a square
// icon frame. A projective transform keeps every straight strand straight.
import { writeFileSync, mkdirSync } from 'node:fs';

const points = [[2, 0], [3, 0], [3, 1], [-1, 1], [-1, 2], [4, 2],
  [4, 3], [0, 3], [0, -1], [1, -1], [1, 4], [2, 4]];
const bridges = [
  [[1.61, 1], [2.39, 1]], [[-.39, 1], [.39, 1]],
  [[.61, 2], [1.39, 2]], [[1.61, 3], [2.39, 3]],
  [[0, 1.61], [0, 2.39]], [[1, .61], [1, 1.39]],
  [[1, 2.61], [1, 3.39]], [[2, 1.61], [2, 2.39]],
];
const yaw = 38 * Math.PI / 180;
const cameraDistance = 420;
function project([u, v]) {
  const x = (u - v) * 54 / Math.SQRT2;
  const y = (u + v - 3) * 54 / Math.SQRT2;
  const perspective = cameraDistance / (cameraDistance - x * Math.sin(yaw));
  return [x * Math.cos(yaw) * perspective, y * perspective];
}
function circle([x, y], radius) {
  return Array.from({ length: 48 }, (_, i) => {
    const angle = i * 2 * Math.PI / 48;
    return [x + radius * Math.cos(angle), y + radius * Math.sin(angle)];
  });
}
function ribbon(a, b, width) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const length = Math.hypot(dx, dy);
  const nx = -dy / length * width / 2, ny = dx / length * width / 2;
  return [[a[0] - nx, a[1] - ny], [b[0] - nx, b[1] - ny],
    [b[0] + nx, b[1] + ny], [a[0] + nx, a[1] + ny]];
}
const strand = points.flatMap((p, i) => [ribbon(p, points[(i + 1) % points.length], .44), circle(p, .22)]);
const gaps = bridges.map(([a, b]) => ribbon(a, b, .66));
const overpasses = bridges.flatMap(([a, b]) => [ribbon(a, b, .44), circle(a, .22), circle(b, .22)]);
const projected = strand.flat().map(project);
const xs = projected.map(p => p[0]), ys = projected.map(p => p[1]);
const bounds = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
const scaleX = 336 / (bounds[2] - bounds[0]);
const scaleY = 336 / (bounds[3] - bounds[1]);
const center = [(bounds[0] + bounds[2]) / 2, (bounds[1] + bounds[3]) / 2];
export function iconPoint(point) {
  const [x, y] = project(point);
  return [256 + (x - center[0]) * scaleX, 256 + (y - center[1]) * scaleY];
}
export function path(polygons) {
  return polygons.map(polygon => polygon.map((point, i) => {
    const [x, y] = iconPoint(point);
    return `${i ? 'L' : 'M'}${x.toFixed(3)} ${y.toFixed(3)}`;
  }).join('') + 'Z').join('\n      ');
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Checkmark endless knot tilted in perspective">
  <!-- Generated by scripts/generate-check-knot-tilted.mjs; edit the generator. -->
  <defs>
    <linearGradient id="face" x1="120" y1="256" x2="392" y2="256" gradientUnits="userSpaceOnUse">
      <stop stop-color="#CAD1DB"/>
      <stop offset="1" stop-color="#FFFFFF"/>
    </linearGradient>
    <mask id="weave" maskUnits="userSpaceOnUse" x="0" y="0" width="512" height="512">
      <path fill="#FFFFFF" d="${path(strand)}"/>
      <path fill="#000000" d="${path(gaps)}"/>
      <path fill="#FFFFFF" d="${path(overpasses)}"/>
    </mask>
  </defs>
  <rect width="512" height="512" rx="112" fill="#191A20"/>
  <rect width="512" height="512" fill="url(#face)" mask="url(#weave)"/>
</svg>
`;
const directory = new URL('../web/brand/check-knot-tilted/', import.meta.url);
mkdirSync(directory, { recursive: true });
writeFileSync(new URL('icon.svg', directory), svg);
