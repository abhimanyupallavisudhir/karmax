// Review-only explorations; preserve the installed brand and its source geometry.
// SVGs: node scripts/generate-gold-logo-options.mjs
// PNGs + comparison: append the path to an installed sharp module (index.js).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const output = new URL('../design/gold-logo-options/', import.meta.url);
mkdirSync(output, { recursive: true });
const options = [
  ['gold-check', '01 / Gold checks', false, false],
  ['gold-arrow', '02 / Gold arrow', true, false],
  ['bold-gold-check', '03 / Bold gold checks', false, true],
  ['bold-gold-arrow', '04 / Bold gold arrow', true, true],
];
const assets = [];
for (const [id, label, arrow, bold] of options) {
  let svg = readFileSync(new URL(`../web/brand/check-knot-purple${arrow ? '-arrow' : ''}/icon.svg`, import.meta.url), 'utf8');
  svg = svg.replace(/aria-label="[^"]*"/, `aria-label="${label.slice(5)} on a perspective knot"`)
    .replace(/<!--.*?-->/s, '<!-- Generated by scripts/generate-gold-logo-options.mjs. -->')
    .replace('#681B98', '#FFD43B');
  if (bold) {
    // Six units of added width retain the channels. A dark keyline keeps the
    // warmer, thicker inlay separate from the knot at antialiased edges.
    svg = svg.replace('#CAD1DB', '#82798F').replace('#FFFFFF"/>', '#BAB2C7"/>');
    const inlay = svg.match(/<path fill="#FFD43B" d="([^"]+)"\/>/);
    if (!inlay) throw new Error(`Missing inlay: ${id}`);
    svg = svg.replace(inlay[0], `<path fill="#FFD43B" stroke="#181220" stroke-width="14" stroke-linejoin="round" d="${inlay[1]}"/>
  <path fill="#FFD43B" stroke="#FFD43B" stroke-width="6" stroke-linejoin="round" d="${inlay[1]}"/>`)
      .replace('fill="#191A20"/>', 'fill="#181220"/>\n  <g transform="translate(256 256) scale(1.12) translate(-256 -256)">')
      .replace('</svg>', '</g>\n</svg>');
  }
  writeFileSync(new URL(`${id}.svg`, output), svg);
  assets.push({ id, label, svg, bold });
}

if (process.argv[2]) {
  const { default: sharp } = await import(pathToFileURL(process.argv[2]).href);
  const width = 1440, height = 1010;
  const layers = [];
  const text = [];
  const label = (x, y, value, size = 18, color = '#BEB6CE') =>
    text.push(`<text x="${x}" y="${y}" font-family="DejaVu Sans, sans-serif" font-size="${size}" fill="${color}">${value}</text>`);
  label(48, 64, 'GOLD / CHECK + ARROW', 32, '#FFF5CE');
  label(48, 99, 'Original geometry above. Stronger small-size options below. All small icons shown at actual pixel size.');
  for (let i = 0; i < assets.length; i++) {
    const { id, label: title, svg, bold } = assets[i];
    const x = 48 + (i % 2) * 700, y = 145 + Math.floor(i / 2) * 405;
    const png = await sharp(Buffer.from(svg)).resize(512, 512).png().toBuffer();
    writeFileSync(new URL(`${id}.png`, output), png);
    layers.push({ input: await sharp(Buffer.from(svg)).resize(280, 280).png().toBuffer(), left: x, top: y });
    label(x, y + 316, title, 24, '#FFF5CE');
    label(x, y + 348, bold ? 'Larger mark / thicker gold / muted knot' : 'Original geometry / bright gold inlays', 17);
    label(x + 315, y + 30, 'SMALL-SIZE CHECK', 15);
    let cursor = x + 315;
    for (const size of [16, 24, 32, 48, 64]) {
      layers.push({ input: await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer(), left: cursor, top: y + 65 + Math.floor((64 - size) / 2) });
      label(cursor, y + 153, String(size), 13);
      cursor += size + 19;
    }
    const original = readFileSync(new URL(`../web/brand/check-knot-purple${i % 2 ? '-arrow' : ''}/icon.svg`, import.meta.url));
    label(x + 315, y + 204, 'Previous purple / 32 px', 15);
    layers.push({ input: await sharp(original).resize(32, 32).png().toBuffer(), left: x + 315, top: y + 223 });
  }
  label(48, 976, 'Gold #FFD43B     /     Bold options trade silver brightness for clearer checks and arrows.', 17);
  layers.push({ input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">${text.join('')}</svg>`), left: 0, top: 0 });
  await sharp({ create: { width, height, channels: 4, background: '#100D17' } }).composite(layers).png().toFile(new URL('comparison.png', output).pathname);
}
