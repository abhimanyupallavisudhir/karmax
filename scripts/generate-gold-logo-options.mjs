// Generate review artwork and the matching selectable installation brand assets.
// SVGs: node scripts/generate-gold-logo-options.mjs
// PNGs + comparison: append the resolved entry path of an installed sharp module.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const output = new URL('../design/gold-logo-options/', import.meta.url);
mkdirSync(output, { recursive: true });
const options = [
  ['gold-check', '01 / Gold checks', false, false],
  ['gold-arrow', '02 / Gold arrow', true, false],
  ['bold-gold-check', '03 / Bold gold checks', false, true],
  ['bold-gold-arrow', '04 / Bold gold arrow', true, true],
  ['royal-gold-check', '05 / Rich gold checks', false, true, true],
  ['royal-gold-arrow', '06 / Rich gold arrow', true, true, true],
];
const assets = [];
for (const [id, label, arrow, bold, rich = false] of options) {
  let svg = readFileSync(new URL(`../web/brand/check-knot-purple${arrow ? '-arrow' : ''}/icon.svg`, import.meta.url), 'utf8');
  svg = svg.replace(/aria-label="[^"]*"/, `aria-label="${label.slice(5)} on a perspective knot"`)
    .replace(/<!--.*?-->/s, '<!-- Generated by scripts/generate-gold-logo-options.mjs. -->')
    .replace('#681B98', '#FFD43B');
  const inlay = svg.match(/<path fill="#FFD43B" d="([^"]+)"\/>/);
  if (!inlay) throw new Error(`Missing inlay: ${id}`);
  let shape = inlay[1];
  if (arrow) {
    // Construct a wider, longer, swept head in screen space, with a visible
    // neck on BOTH sides. The original narrow shoulders read as a blunt tip.
    const center = [382, 144], axis = [.8, -.6], normal = [.6, .8];
    const point = (forward, side) => center.map((v, i) =>
      (v + forward * axis[i] + side * normal[i]).toFixed(3)).join(' ');
    const head = [point(0, -19), point(-14, -38), point(72, 0), point(-14, 38), point(0, 19)];
    const lower = `M136.739 237.516L178.466 271.293L${head.join('L')}L178.466 310.221L115.156 256.000Z`;
    shape = shape.slice(0, shape.indexOf('Z') + 1) + lower;
  }
  const ink = rich ? 'url(#gold)' : '#FFD43B';
  const weight = rich ? 10 : bold ? 6 : 0;
  svg = svg.replace(inlay[0], `<path fill="${ink}" stroke="#120D19" stroke-width="${weight + 8}" stroke-linejoin="miter" stroke-miterlimit="3" d="${shape}"/>
  <path fill="${ink}"${weight ? ` stroke="${ink}" stroke-width="${weight}" stroke-linejoin="miter" stroke-miterlimit="3"` : ''} d="${shape}"/>`);
  if (rich) {
    // A restrained amber-to-champagne ramp: warm metal without glossy bands.
    svg = svg.replace('<defs>', `<defs>
    <linearGradient id="gold" x1="120" y1="330" x2="340" y2="115" gradientUnits="userSpaceOnUse">
      <stop stop-color="#A96716"/>
      <stop offset=".42" stop-color="#CC9024"/>
      <stop offset=".76" stop-color="#E3B344"/>
      <stop offset="1" stop-color="#F2CF78"/>
    </linearGradient>`);
  }
  if (bold) {
    svg = svg.replace('#CAD1DB', '#82798F').replace('#FFFFFF"/>', '#BAB2C7"/>');
    svg = svg.replace('fill="#191A20"/>', 'fill="#181220"/>\n  <g transform="translate(256 256) scale(1.12) translate(-256 -256)">')
      .replace('</svg>', '</g>\n</svg>');
  }
  writeFileSync(new URL(`${id}.svg`, output), svg);
  const brandDir = new URL(`../web/brand/${id}/`, import.meta.url);
  mkdirSync(brandDir, { recursive: true });
  writeFileSync(new URL('icon.svg', brandDir), svg);
  assets.push({ id, label, svg, bold, rich });
}

if (process.argv[2]) {
  const { default: sharp } = await import(pathToFileURL(process.argv[2]).href);
  const width = 1440, height = 1415;
  const layers = [];
  const text = [];
  const label = (x, y, value, size = 18, color = '#BEB6CE') =>
    text.push(`<text x="${x}" y="${y}" font-family="DejaVu Sans, sans-serif" font-size="${size}" fill="${color}">${value}</text>`);
  label(48, 64, 'GOLD / CHECK + ARROW', 32, '#FFF5CE');
  label(48, 99, 'Dark outlines throughout. Sculpted arrowheads. Small icons shown at actual pixel size.');
  for (let i = 0; i < assets.length; i++) {
    const { id, label: title, svg, bold, rich } = assets[i];
    const x = 48 + (i % 2) * 700, y = 145 + Math.floor(i / 2) * 405;
    const png = await sharp(Buffer.from(svg)).resize(512, 512).png().toBuffer();
    writeFileSync(new URL(`${id}.png`, output), png);
    const brandDir = new URL(`../web/brand/${id}/`, import.meta.url);
    writeFileSync(new URL('icon-512.png', brandDir), png);
    for (const [file, size] of [['icon-192.png', 192], ['apple-touch-icon.png', 180]]) {
      await sharp(Buffer.from(svg)).resize(size, size).png().toFile(new URL(file, brandDir).pathname);
    }
    layers.push({ input: await sharp(Buffer.from(svg)).resize(280, 280).png().toBuffer(), left: x, top: y });
    label(x, y + 316, title, 24, '#FFF5CE');
    label(x, y + 348, rich ? 'Heavier strokes / amber-to-champagne gold' : bold ? 'Larger mark / thicker gold / muted knot' : 'Bright gold / dark outlines / silver knot', 17);
    label(x + 315, y + 30, 'SMALL-SIZE CHECK', 15);
    let cursor = x + 315;
    for (const size of [16, 24, 32, 48, 64]) {
      layers.push({ input: await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer(), left: cursor, top: y + 65 + Math.floor((64 - size) / 2) });
      label(cursor, y + 153, String(size), 13);
      cursor += size + 19;
    }
    const original = readFileSync(new URL(`../web/brand/check-knot-purple${i % 2 ? '-arrow' : ''}/icon.svg`, import.meta.url));
    label(x + 315, y + 204, 'Previous purple / 32 px', 15);
    layers.push({ input: await sharp(original).resize(32, 32).png().toBuffer(), left: x + 315, top: y + 223 });
  }
  label(48, 1381, '05 + 06: richer gold trades some luminance for depth; heavier strokes preserve visibility.', 17);
  layers.push({ input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">${text.join('')}</svg>`), left: 0, top: 0 });
  await sharp({ create: { width, height, channels: 4, background: '#100D17' } }).composite(layers).png().toFile(new URL('comparison.png', output).pathname);
}
