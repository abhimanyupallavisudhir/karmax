/** The VM user and home, the same as an E2B sandbox's: the remote agent
 * runtime, the memory guard and every prompt already assume them. */
export const VM_USER = 'user';
export const VM_HOME = '/home/user';
/** karmax's sshd port. Not 22: Fly's own `hallpass` SSH listens there. */
export const VM_SSH_PORT = 2222;
export const VM_ETC = '/etc/karmax';
/** How the provisioning script names the step that failed (vmProvisionFailure reads it). */
const PROVISION_FAILED = 'karmax provisioning failed';

/**
 * Runs as root at every boot, before anything else needs the machine: the VM
 * user (passwordless sudo, as on E2B), the world's volume as its home, and an
 * sshd that accepts only this world's key and presents only this world's host
 * key — both generated by karmax and delivered with the machine (Fly `files`,
 * Hetzner cloud-init), so the connection is pinned with no trust on first use.
 * Quick and idempotent; on a stock image it installs sshd and sudo once.
 */
export function vmBootScript(options: { foreground: boolean }): string {
  return `#!/bin/sh
# karmax VM boot (src/world/vm/provision.ts). Runs as root at every boot.
set -u
export DEBIAN_FRONTEND=noninteractive
K=${VM_ETC}
need=""
[ -x /usr/sbin/sshd ] || need="$need openssh-server"
command -v sudo > /dev/null 2>&1 || need="$need sudo"
if [ -n "$need" ]; then
  for attempt in 1 2 3; do
    apt-get update -qq && apt-get install -y -qq --no-install-recommends ca-certificates $need && break
    sleep 5
  done
fi
if ! id ${VM_USER} > /dev/null 2>&1; then
  useradd -M -d ${VM_HOME} -s /bin/bash -u 1000 ${VM_USER} 2> /dev/null || useradd -M -d ${VM_HOME} -s /bin/bash ${VM_USER}
fi
printf '%s\\n' '${VM_USER} ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/karmax-user && chmod 440 /etc/sudoers.d/karmax-user
# The world's volume is the user's home. Fly mounts it itself; a Hetzner,
# AWS or Google Cloud volume is named by the device file the boot delivers.
# AWS and Google Cloud attach a new volume unformatted: it gets a filesystem
# once (\`blkid -p\` exits 2 only when the device holds no signature at all).
# Without its volume the machine never starts sshd, so it reads as broken and
# is replaced: a world must never run on the root disk instead.
mkdir -p ${VM_HOME}
if [ -s "$K/volume-device" ]; then
  device=$(cat "$K/volume-device")
  for i in $(seq 1 360); do [ -e "$device" ] && break; sleep 0.5; done
  [ -e "$device" ] || { echo "the world's volume $device never appeared" >&2; exit 1; }
  blkid -p "$device" > /dev/null 2>&1; [ $? = 2 ] && mkfs.ext4 -q -m 0 "$device"
  grep -q " ${VM_HOME} " /etc/fstab || printf '%s ${VM_HOME} ext4 discard,nofail,defaults 0 2\\n' "$device" >> /etc/fstab
  mountpoint -q ${VM_HOME} || mount ${VM_HOME} || { echo "could not mount the world's volume $device" >&2; exit 1; }
fi
# A volume grown while the machine was off grows its filesystem now.
source=$(findmnt -no SOURCE ${VM_HOME} 2> /dev/null) && [ -n "$source" ] && resize2fs "$source" > /dev/null 2>&1
chown ${VM_USER}:${VM_USER} ${VM_HOME}
[ -e ${VM_HOME}/.profile ] || { cp -rn /etc/skel/. ${VM_HOME}/ 2> /dev/null; chown -R ${VM_USER}:${VM_USER} ${VM_HOME}/.bashrc ${VM_HOME}/.profile ${VM_HOME}/.bash_logout 2> /dev/null; }
chmod 600 "$K/ssh_host_ed25519_key"
mkdir -p /etc/ssh/sshd_config.d /run/sshd
cat > /etc/ssh/sshd_config.d/00-karmax.conf << 'EOF'
Port ${VM_SSH_PORT}
HostKey ${VM_ETC}/ssh_host_ed25519_key
AuthorizedKeysFile ${VM_ETC}/authorized_keys
AllowUsers ${VM_USER}
PermitRootLogin no
PasswordAuthentication no
KbdInteractiveAuthentication no
MaxSessions 256
MaxStartups 64:30:256
ClientAliveInterval 30
ClientAliveCountMax 4
AllowTcpForwarding local
X11Forwarding no
PrintMotd no
EOF
grep -q '^Include /etc/ssh/sshd_config.d' /etc/ssh/sshd_config 2> /dev/null || sed -i '1i Include /etc/ssh/sshd_config.d/*.conf' /etc/ssh/sshd_config
touch "$K/booted"
${options.foreground
    // The machine's main process: sshd, restarted should anything stop it,
    // and stopped at once when the machine is (Fly kills it 15 s after a stop).
    ? "trap 'kill $sshd 2> /dev/null; exit 0' TERM INT\nwhile :; do /usr/sbin/sshd -D -e & sshd=$!; wait $sshd; sleep 1; done"
    : '(systemctl restart ssh || systemctl restart sshd || /usr/sbin/sshd) > /dev/null 2>&1'}
`;
}

/** What every boot needs on the machine: its keys, its volume's device, and
 * the boot script. */
function bootFiles(keys: { hostPrivateKey: string; authorizedKey: string }, device?: string): Array<[string, string, string]> {
  return [
    [`${VM_ETC}/ssh_host_ed25519_key`, keys.hostPrivateKey, '0600'],
    [`${VM_ETC}/authorized_keys`, `${keys.authorizedKey}\n`, '0644'],
    ...(device ? [[`${VM_ETC}/volume-device`, device, '0644'] as [string, string, string]] : []),
    ['/var/lib/cloud/scripts/per-boot/karmax-boot.sh', vmBootScript({ foreground: false }), '0755'],
  ];
}

/** cloud-init user data (Hetzner, AWS): the boot files; cloud-init runs the
 * boot script at every boot from its per-boot directory. */
export function cloudInit(keys: { hostPrivateKey: string; authorizedKey: string }, device?: string): string {
  const file = ([path, content, permissions]: [string, string, string]) =>
    `  - path: ${path}\n    permissions: '${permissions}'\n    encoding: b64\n    content: ${Buffer.from(content).toString('base64')}\n`;
  return `#cloud-config\nwrite_files:\n${bootFiles(keys, device).map(file).join('')}`;
}

/** A startup script (Google Cloud, whose Debian images run one at every boot
 * instead of cloud-init): it writes the boot files, then runs the boot script. */
export function startupScript(keys: { hostPrivateKey: string; authorizedKey: string }, device?: string): string {
  const files = bootFiles(keys, device).map(([path, content, permissions]) =>
    `mkdir -p ${quote(path.replace(/\/[^/]+$/, ''))} && printf %s ${quote(Buffer.from(content).toString('base64'))} | base64 -d > ${quote(path)} && chmod ${permissions} ${quote(path)}`);
  return `#!/bin/sh\n# karmax VM boot files (src/world/vm/provision.ts)\nset -e\n${files.join('\n')}\nexec /var/lib/cloud/scripts/per-boot/karmax-boot.sh\n`;
}

/** The render smoke test of `environments/browser`, read when a script is made:
 * an install without it (an old image) fails provisioning, not boot. */
let smoke: string | undefined;
function smokeTest(): string {
  return smoke ??= fs.readFileSync(fileURLToPath(new URL('../../../environments/browser/smoke.mjs', import.meta.url)), 'utf8');
}

/**
 * Everything the E2B template `environments/browser` bakes, for a stock
 * Debian machine: system packages, Google Chrome, the pinned Node/npm pair at
 * the path the remote runtime looks for, the browser MCP servers with
 * Playwright's Chromium, and the pinned agent CLIs — then the same render
 * smoke test. Root, idempotent: a machine (or a Fly image / Hetzner snapshot
 * built from one) that already ran this exact script skips it.
 */
export function vmProvisionScript(stamp = vmProvisionStamp()): string {
  const node = PINNED_REMOTE_NODE_VERSION;
  const root = `/opt/karmax/node-${node}`;
  return `#!/bin/bash
# karmax VM provisioning (src/world/vm/provision.ts), as root.
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
# Name the step that failed (retry names its own): the error karmax reports leads with it (vmProvisionFailure).
trap 'echo "${PROVISION_FAILED} (status $?): $BASH_COMMAND" >&2' ERR
# No package may restart a running service: on Fly, sshd is the machine's main process.
printf '#!/bin/sh\nexit 101\n' > /usr/sbin/policy-rc.d && chmod 755 /usr/sbin/policy-rc.d
trap 'rm -f /usr/sbin/policy-rc.d' EXIT
retry() {
  for attempt in 1 2 3 4; do "$@" && return 0; echo "attempt $attempt failed: $*" >&2; [ $attempt = 4 ] || sleep $((attempt * 10)); done
  echo "${PROVISION_FAILED} (status 1): $*" >&2; return 1
}
# A stalled mirror is given up on after 30 s and retried, here and in the
# world's own setup commands.
cat > /etc/apt/apt.conf.d/80karmax << 'EOF'
Acquire::Retries "3";
Acquire::http::Timeout "30";
Acquire::https::Timeout "30";
EOF
# A source that cannot be reached fails the update: by default it is only a
# warning, and every install after it fails with "Unable to locate package".
apt_update() { apt-get update -qq --error-on=any; }
retry apt_update
# What the E2B template's base image has (node:22-bookworm, i.e.
# buildpack-deps), so project setup written for E2B runs here unchanged:
# build tools and the -dev libraries native packages compile against,
# ImageMagick, gh, and Python with pip and venv — pip may install outside a
# virtualenv, as on E2B.
retry apt-get install -y -qq --no-install-recommends \\
  ca-certificates curl wget gnupg netbase git openssh-client openssh-server sudo procps less file patch \\
  xz-utils bzip2 unzip zip rsync jq util-linux e2fsprogs bubblewrap gh \\
  build-essential autoconf automake libtool dpkg-dev pkg-config imagemagick \\
  libbz2-dev libcurl4-openssl-dev libdb-dev libevent-dev libffi-dev libgdbm-dev libglib2.0-dev libgmp-dev libjpeg-dev \\
  libkrb5-dev liblzma-dev libmagickcore-dev libmagickwand-dev libmaxminddb-dev libncurses5-dev libncursesw5-dev libpng-dev \\
  libpq-dev default-libmysqlclient-dev libreadline-dev libsqlite3-dev libssl-dev libwebp-dev libxml2-dev libxslt1-dev \\
  libyaml-dev zlib1g-dev python3 python3-dev python3-pip python3-venv python-is-python3
printf '[global]\nbreak-system-packages = true\n' > /etc/pip.conf
if [ "$(dpkg --print-architecture)" = amd64 ] && ! command -v google-chrome > /dev/null; then
  install -d -m 0755 /etc/apt/keyrings
  retry sh -c 'curl -fsSL https://dl.google.com/linux/linux_signing_key.pub | gpg --batch --yes --dearmor -o /etc/apt/keyrings/google-chrome.gpg'
  # From Hetzner's network dl.google.com answers plain HTTP never and HTTPS at
  # ~100 KB/s, so the ~140 MB package times out (pramana#39, 2026-10-13).
  # Google's download CDN serves the same repository at full speed; apt checks
  # it against Google's key all the same. dl.google.com stays the fallback.
  chrome_from() {
    echo "deb [arch=amd64 signed-by=/etc/apt/keyrings/google-chrome.gpg] $1 stable main" > /etc/apt/sources.list.d/google-chrome.list
    apt_update && apt-get install -y -qq --no-install-recommends google-chrome-stable
  }
  retry chrome_from https://edgedl.me.gvt1.com/edgedl/linux/chrome/deb/ || retry chrome_from https://dl.google.com/linux/chrome/deb/
  # Chrome's package adds dl.google.com as a source of its own: without it
  # the world's own apt commands never wait on Google. It is not re-added.
  rm -f /etc/apt/sources.list.d/google-chrome.list /etc/apt/sources.list.d/google-chrome.sources
fi
if ! node -e 'process.exit(Number(process.versions.node.split(".")[0]) >= 22 ? 0 : 1)' 2> /dev/null; then
  arch=$(uname -m | sed 's/x86_64/x64/; s/aarch64/arm64/')
  retry sh -c "curl -fsSL https://nodejs.org/dist/v${node}/node-v${node}-linux-$arch.tar.xz | tar -xJ -C /usr/local --strip-components=1"
fi
mkdir -p ${quote(`${root}/bin`)} /opt/karmax/browser /opt/karmax/bin /opt/karmax/agents /opt/karmax/browsers
retry npm install --prefix ${quote(root)} --no-audit --no-fund --omit=dev ${quote(`node@${node}`)} ${quote(`npm@${PINNED_REMOTE_NPM_VERSION}`)}
${[['node', '../node_modules/node/bin/node'], ['npm', '../node_modules/npm/bin/npm-cli.js'], ['npx', '../node_modules/npm/bin/npx-cli.js']]
    .map(([name, target]) => `ln -sfn ${quote(target!)} ${quote(`${root}/bin/${name}`)}`).join('\n')}
export PATH=${quote(`${root}/bin`)}:$PATH
retry npm install --prefix /opt/karmax/browser --no-audit --no-fund --omit=dev ${[
    `playwright@${PLAYWRIGHT_VERSION}`, `@playwright/mcp@${PLAYWRIGHT_MCP_VERSION}`, `chrome-devtools-mcp@${CHROME_DEVTOOLS_MCP_VERSION}`,
  ].map(quote).join(' ')}
retry env PLAYWRIGHT_BROWSERS_PATH=/opt/karmax/browsers /opt/karmax/browser/node_modules/.bin/playwright install --with-deps chromium
ln -sfn /opt/karmax/browser/node_modules/.bin/playwright-mcp /opt/karmax/bin/playwright-mcp
ln -sfn /opt/karmax/browser/node_modules/.bin/chrome-devtools-mcp /opt/karmax/bin/chrome-devtools-mcp
retry npm install --prefix /opt/karmax/agents --no-audit --no-fund --omit=dev ${[
    `@anthropic-ai/claude-code@${installedClaudeCodeVersion()}`, `@openai/codex@${CODEX_VERSION}`, OPENCODE_PACKAGE,
  ].map(quote).join(' ')}
for name in claude codex opencode; do ln -sfn "/opt/karmax/agents/node_modules/.bin/$name" "/opt/karmax/bin/$name"; done
cat > /opt/karmax/smoke.mjs << 'KARMAX_SMOKE'
${smokeTest().trim()}
KARMAX_SMOKE
chmod -R a+rX /opt/karmax
PLAYWRIGHT_BROWSERS_PATH=/opt/karmax/browsers node /opt/karmax/smoke.mjs
cat > /etc/profile.d/karmax.sh << 'EOF'
export PATH=/opt/karmax/bin:$PATH
export PLAYWRIGHT_BROWSERS_PATH=/opt/karmax/browsers
export KARMAX_BROWSER_BIN=/opt/karmax/bin
EOF
touch ${quote(stamp)}
`;
}

/**
 * What a failed script's log says went wrong, for a person: the step that
 * failed and the lines that read as errors (apt's `E:`/`W:`, npm's `ERR!`,
 * curl's and others' `error`), not the last screen of package output — the
 * cause of pramana#39 (`W: Failed to fetch …`) sat under forty `Setting up …`
 * lines. Falls back to the log's tail.
 */
export function vmProvisionFailure(log: string, status: string | number): string {
  const lines = log.replace(/\r/g, '').split('\n').map((line) => line.trimEnd()).filter(Boolean);
  // The last report is the step; the trap also sees `retry` itself return.
  const step = lines.filter((line) => line.startsWith(PROVISION_FAILED) && !/\): return \d+$/.test(line)).at(-1)?.match(/\(status (\d+)\): (.*)$/);
  const errors = [...new Set(lines.filter((line) => !line.startsWith(PROVISION_FAILED)
    && /^(E|W|Err):|\bERR!|\berror\b|\bfatal\b|\bfailed\b|\bnot found\b|\bunable to\b|\bcannot\b|\bno such file\b|\bpermission denied\b|^curl: \(\d+\)|^gpg: /i.test(line)))];
  const detail = (errors.length ? errors.slice(-12) : lines.slice(-15)).map((line) => line.slice(0, 300)).join('\n');
  const head = step ? `\`${step[2]!.replace(/\s+/g, ' ').slice(0, 200)}\` exited with status ${step[1]}` : `the script exited with status ${status}`;
  return `${head}:\n${detail}`;
}

/** Present on a machine that ran this exact provisioning script. */
export function vmProvisionStamp(): string {
  return `/opt/karmax/.vm-provisioned-${vmProvisionVersion()}`;
}

let version: string | undefined;
/** Short content hash of the provisioning script: names Hetzner snapshots, the
 * Fly image tag and stamps. It hashes the script a machine runs, never the
 * function's compiled source, which differs between tsx and Vitest. */
export function vmProvisionVersion(): string {
  if (!version) {
    // The stamp names the version, so the script is hashed with a placeholder for it.
    const script = vmProvisionScript('/opt/karmax/.vm-provisioned') + JSON.stringify([PINNED_REMOTE_NODE_VERSION, PINNED_REMOTE_NPM_VERSION,
      PLAYWRIGHT_VERSION, PLAYWRIGHT_MCP_VERSION, CHROME_DEVTOOLS_MCP_VERSION, installedClaudeCodeVersion(), CODEX_VERSION,
      OPENCODE_PACKAGE, smokeTest()]);
    version = crypto.createHash('sha256').update(script).digest('hex').slice(0, 12);
  }
  return version;
}
